#!/usr/bin/env python3
"""把编译好的 classes.dex 生成为 C++ 头文件（字节嵌入 .so）。"""
import os
import sys


def main() -> None:
    if len(sys.argv) != 3:
        print("usage: gen_dex_header.py <classes.dex> <out header>", file=sys.stderr)
        sys.exit(2)
    src, dst = sys.argv[1], sys.argv[2]
    with open(src, "rb") as f:
        data = f.read()
    os.makedirs(os.path.dirname(dst) or ".", exist_ok=True)
    with open(dst, "w", encoding="ascii") as f:
        f.write("// generated by tools/gen_dex_header.py - do not edit\n")
        f.write("#pragma once\n#include <cstddef>\n\nnamespace clipshield {\n")
        f.write("inline constexpr unsigned char kDexBytes[] = {")
        f.write(",".join(str(b) for b in data))
        f.write("};\ninline constexpr size_t kDexSize = sizeof(kDexBytes);\n}  // namespace clipshield\n")
    print(f"gen_dex_header: {len(data)} bytes -> {dst}")


if __name__ == "__main__":
    main()
